"""CIE 1931 colour-matching tables and blackbody colour reference values.

Produces two things from the official CIE 1931 2-degree standard observer data (via colour-science):

  1. Sources/BlackHoleKit/Radiometry/CIE1931Tables.swift: the table the renderer integrates, 380-780 nm
     at 5 nm spacing (generated; do not edit by hand).
  2. Tests/BlackHoleKitTests/Fixtures/planck_color.json: reference XYZ, chromaticity and linear sRGB for
     blackbodies, integrated here at 1 nm with numpy (independent of the Swift integration).

Run from the repository root:  uv run python tools/reference/color.py
"""

import json
import warnings
from pathlib import Path

import numpy as np

warnings.filterwarnings("ignore")
import colour  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
SWIFT_OUT = ROOT / "Sources/BlackHoleKit/Radiometry/CIE1931Tables.swift"
JSON_OUT = ROOT / "Tests/BlackHoleKitTests/Fixtures/planck_color.json"

H = 6.62607015e-34
C = 299792458.0
KB = 1.380649e-23

TEMPERATURES = [1500.0, 2700.0, 4000.0, 5500.0, 6504.0, 9000.0, 15000.0, 40000.0, 1e6, 1e7]


def planck_lambda(wavelength_m, temperature):
    """Spectral radiance B_lambda in W m^-2 sr^-1 m^-1."""
    a = 2 * H * C**2 / wavelength_m**5
    return a / np.expm1(H * C / (wavelength_m * KB * temperature))


def main():
    cmfs = colour.MSDS_CMFS["CIE 1931 2 Degree Standard Observer"]
    lam_nm = np.arange(380, 781, 1)
    table = np.array([cmfs[float(w)] for w in lam_nm])  # columns x, y, z

    # --- Swift table at 5 nm
    five = np.arange(380, 781, 5)
    rows = [cmfs[float(w)] for w in five]
    lines = [
        "// Generated by tools/reference/color.py from the CIE 1931 2-degree standard observer. Do not edit.",
        "",
        "/// CIE 1931 2° colour-matching functions, 380–780 nm at 5 nm spacing.",
        "enum CIE1931 {",
        "    static let firstWavelengthNanometers = 380.0",
        "    static let stepNanometers = 5.0",
        "    /// x̄, ȳ, z̄ at each wavelength.",
        "    static let table: [SIMD3<Double>] = [",
    ]
    for row in rows:
        lines.append(f"        SIMD3({row[0]:.7f}, {row[1]:.7f}, {row[2]:.7f}),")
    lines += ["    ]", "}", ""]
    SWIFT_OUT.parent.mkdir(parents=True, exist_ok=True)
    SWIFT_OUT.write_text("\n".join(lines))

    # --- Reference colours at 1 nm
    matrix = np.array(colour.models.RGB_COLOURSPACES["sRGB"].matrix_XYZ_to_RGB)
    lam_m = lam_nm * 1e-9
    out = []
    for t in TEMPERATURES:
        b = planck_lambda(lam_m, t)
        xyz = np.array([np.trapezoid(b * table[:, k], lam_m) for k in range(3)])
        x, y = xyz[0] / xyz.sum(), xyz[1] / xyz.sum()
        rgb = matrix @ xyz
        out.append({"T": t, "X": xyz[0], "Y": xyz[1], "Z": xyz[2], "x": x, "y": y, "rgb": rgb.tolist()})
    JSON_OUT.write_text(json.dumps({"matrix_XYZ_to_sRGB": matrix.tolist(), "blackbodies": out}, indent=1) + "\n")
    print(f"wrote {SWIFT_OUT.name} ({len(rows)} rows) and {JSON_OUT.name} ({len(out)} blackbodies)")
    for o in out:
        print(f"T={o['T']:>10.0f}  x={o['x']:.4f} y={o['y']:.4f}  rgb/Y=" + " ".join(f"{v / o['Y']:.3f}" for v in o["rgb"]))


if __name__ == "__main__":
    main()
